async function authHeader(): Promise<HeadersInit> {
  if (!hasSupabaseEnv()) return {};
  const {
    data: { session },
  } = await supabase().auth.getSession();
  return session?.access_token
    ? { Authorization: `Bearer ${session.access_token}` }
    : {};
}

async function request<T>(
  path: string,
  init: RequestInit = {}
): Promise<T> {
  const auth = await authHeader();
  // Only declare a JSON content-type when we actually have a body to
  // serialize. Fastify's JSON parser rejects requests that carry
  // `Content-Type: application/json` with an empty body
  // (FST_ERR_CTP_EMPTY_JSON_BODY). Body-less POSTs (Suggest title,
  // Reset title, Start new draft, etc.) should send no Content-Type.
  const headers: Record<string, string> = { ...auth };
  if (init.body != null) {
    headers["Content-Type"] = "application/json";
  }
  if (init.headers) {
    Object.assign(headers, init.headers as Record<string, string>);
  }
  const res = await fetch(`${BASE}/api${path}`, { ...init, headers });
  if (res.status === 401 && hasSupabaseEnv()) {
    // Token expired/invalid — clear the stale session and bounce to sign-in
    // so the user isn't stranded on a silently-empty or perpetually-loading
    // page.
    try {
      await supabase().auth.signOut();
    } catch {
      /* ignore */
    }
    if (typeof window !== "undefined" && !window.location.pathname.startsWith("/sign-in")) {
      window.location.assign("/sign-in");
    }
    throw new Error("Your session expired — please sign in again.");
  }
  if (!res.ok) {
    const body = await res.text();
    throw new Error(`${res.status} ${res.statusText} — ${body.slice(0, 240)}`);
  }
  if (res.status === 204) return undefined as unknown as T;
  return (await res.json()) as T;
}

